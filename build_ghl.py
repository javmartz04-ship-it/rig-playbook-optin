#!/usr/bin/env python3
"""Builds the GoHighLevel loaders in ghl/*.js from the source pages.

Each GHL funnel page holds ONE line of custom code:
    <script src="https://javmartz04-ship-it.github.io/rig-playbook-optin/ghl/<page>.js"></script>
The loader mounts the whole page (styles, markup, scripts) on top of the empty GHL page, so every later
edit is: change the source .html, run this script, push. Nothing is ever re-pasted in GHL.

Run:  python3 build_ghl.py
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).parent
BASE = 'https://javmartz04-ship-it.github.io/rig-playbook-optin/'
# source file -> (loader name, GHL path it lives at)
PAGES = {
    'index.html':  'optin',
    'simple.html': 'optin-simple',
    'vsl.html':    'watch',
    'book.html':   'call',
    'thanks.html': 'booked',
}
# links between pages, rewritten to the GHL slugs
SLUGS = {
    "NEXT: 'vsl.html'": "NEXT: '/playbook-watch'",
    'href="book.html"': 'href="/playbook-call"',
    "var THANKS = 'thanks.html'": "var THANKS = '/playbook-booked'",
}

def absolutize(t):
    t = re.sub(r'''(["'(])assets/''', lambda m: m.group(1) + BASE + 'assets/', t)
    t = t.replace('`assets/', '`' + BASE + 'assets/')
    return t

def build(src, name, swaps=()):
    html = (ROOT / src).read_text()
    for a, b in swaps:
        assert a in html, a
        html = html.replace(a, b)
    for a, b in SLUGS.items():
        html = html.replace(a, b)
    # inline the shared stylesheet
    css_link = re.search(r'<link rel="stylesheet" href="pages\.css[^"]*">', html)
    if css_link:
        html = html.replace(css_link.group(0), '<style>' + (ROOT / 'pages.css').read_text() + '</style>')
    html = absolutize(html)
    head = re.search(r'<head>(.*?)</head>', html, re.S).group(1)
    body = re.search(r'<body[^>]*>(.*)</body>', html, re.S).group(1)
    title = re.search(r'<title>(.*?)</title>', head, re.S).group(1)

    scripts = []          # in document order: head scripts first, then body scripts
    def take(m):
        attrs, code = m.group(1), m.group(2)
        srcm = re.search(r'src="([^"]+)"', attrs)
        if srcm:
            data = dict(re.findall(r'(data-[a-z-]+)="([^"]*)"', attrs))
            scripts.append({'src': srcm.group(1), 'attrs': data})
        else:
            scripts.append({'code': code})
        return ''
    head = re.sub(r'<script([^>]*)>(.*?)</script>', take, head, flags=re.S)
    body = re.sub(r'<script([^>]*)>(.*?)</script>', take, body, flags=re.S)
    head = re.sub(r'<title>.*?</title>|<meta charset[^>]*>|<meta name="viewport"[^>]*>', '', head, flags=re.S)
    # captions come from another origin once the page sits on the GHL domain
    body = body.replace('<video id="vmP" controls playsinline>', '<video id="vmP" controls playsinline crossorigin="anonymous">')

    assert not re.search(r'''["'(`]assets/''', head + body + json.dumps(scripts)), src + ': relative asset left'

    js = '''/* Generated by build_ghl.py from %s. Do not edit by hand. */
(function () {
  if (window.__rigpb) return; window.__rigpb = 1;
  var HEAD = %s, BODY = %s, SCRIPTS = %s, TITLE = %s;
  var d = document;
  d.title = TITLE;
  if (!d.querySelector('meta[name=viewport]')) { var m = d.createElement('meta'); m.name = 'viewport'; m.content = 'width=device-width,initial-scale=1'; d.head.appendChild(m); }
  // Hide the empty GHL page; our page is mounted straight on <body>.
  var hide = d.createElement('style');
  hide.textContent = 'body>*:not(#rigpb):not(script):not(style):not(link){display:none!important}html,body{margin:0!important;padding:0!important}';
  d.head.appendChild(hide);
  d.head.insertAdjacentHTML('beforeend', HEAD);
  var root = d.createElement('div'); root.id = 'rigpb'; root.innerHTML = BODY;
  function mount() {
    d.body.appendChild(root);
    SCRIPTS.forEach(function (s) {
      var el = d.createElement('script');
      if (s.src) { el.src = s.src; el.async = true; for (var k in s.attrs) el.setAttribute(k, s.attrs[k]); }
      else el.text = s.code;
      d.body.appendChild(el);
    });
  }
  if (d.body) mount(); else d.addEventListener('DOMContentLoaded', mount);
})();
''' % (src, json.dumps(head), json.dumps(body), json.dumps(scripts), json.dumps(title))
    js = js.replace('</script', '<\\/script')
    out = ROOT / 'ghl' / (name + '.js')
    out.parent.mkdir(exist_ok=True)
    out.write_text(js)
    print('%-12s -> ghl/%s.js  %d KB' % (src, name, len(js) // 1024))

for src, name in PAGES.items():
    build(src, name)

# The same thank-you page for the Book A Call VSL funnel (no Playbook mention, its own tracker name).
build('thanks.html', 'booked-vsl', swaps=[
    (' And keep the Playbook open, it&rsquo;s in your inbox.', ''),
    ('data-funnel="Playbook Thank You"', 'data-funnel="Book A Call Thank You"'),
    ('Watch Before Your Call &middot; 7 Min', 'Watch Before Your Call, 7 Min'),
])
